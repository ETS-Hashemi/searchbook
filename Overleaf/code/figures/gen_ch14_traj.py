def write_example_figures():
    p, v_a, goal, obstacles, prm = worked_example()
    v_best, cands = dwa_command(p, v_a, obstacles, goal, prm, goal)
    # --- velocity space --------------------------------------------------
    boundary = []
    for k in range(361):
        phi = math.radians(k)
        d = np.array([math.cos(phi), math.sin(phi)])
        dist = free_distance(p, d, obstacles, prm.radius, prm.d_max)
        r = min(admissible_speed(dist, prm.a_brake, prm.dt), prm.v_max)
        boundary.append((r * d[0], r * d[1]))
    lo = v_a - prm.a_max * prm.dt
    hi = v_a + prm.a_max * prm.dt
    adm = [c for c in cands if c.admissible]
    inadm = [c for c in cands if not c.admissible]
    L = []
    L.append("% Generated by code/figures/gen_ch14_traj.py -- do not edit by hand.")
    L.append("\\begin{tikzpicture}[font=\\footnotesize]")
    L.append("\\begin{axis}[width=0.5\\textwidth,axis equal image,"
             "xmin=-0.35,xmax=2.25,ymin=-1.15,ymax=1.35,xlabel={$v_x$ [m/s]},ylabel={$v_y$ [m/s]},"
             "grid=major,grid style={black!10},clip=true]")
    L.append("\\addplot[fill=sbGreen!15,draw=sbGreen,thin,forget plot] coordinates {%s} -- cycle;" % polygon(boundary))
    L.append("\\addplot[black!60,dashed,thin,forget plot] coordinates {%s} -- cycle;" % polygon(circle_points((0.0, 0.0), prm.v_max, 90)))
    L.append("\\addplot[sbBlue,very thick,forget plot] coordinates {(%.2f,%.2f) (%.2f,%.2f) (%.2f,%.2f) (%.2f,%.2f)} -- cycle;"
             % (lo[0], lo[1], hi[0], lo[1], hi[0], hi[1], lo[0], hi[1]))
    L.append("\\addplot[only marks,mark=*,mark size=1.6pt,mark options={draw=sbBlue,fill=sbBlue!40},forget plot] coordinates {%s};"
             % polygon([(c.v[0], c.v[1]) for c in adm]))
    L.append("\\addplot[only marks,mark=x,mark size=2.6pt,thick,sbRed,forget plot] coordinates {%s};"
             % polygon([(c.v[0], c.v[1]) for c in inadm]))
    L.append("\\addplot[only marks,mark=square*,mark size=2.6pt,mark options={draw=black,fill=white},forget plot] coordinates {(%.2f,%.2f)};" % (v_a[0], v_a[1]))
    L.append("\\addplot[only marks,mark=star,mark size=4.5pt,very thick,sbOrange,forget plot] coordinates {(%.2f,%.2f)};" % (v_best[0], v_best[1]))
    L.append("\\node[sbannot,text=sbBlue] at (axis cs:1.0,0.68) {$V_d$};")
    L.append("\\node[sbannot,text=sbGreen] at (axis cs:-0.15,0.95) {$V_a$};")
    L.append("\\node[sbannot,text=black!60] at (axis cs:1.55,1.2) {$V_s$};")
    L.append("\\node[sbannot,anchor=north] at (axis cs:%.2f,%.2f) {$\\vel_a$};" % (v_a[0], v_a[1] - 0.06))
    L.append("\\node[sbannot,text=sbOrange,anchor=south west] at (axis cs:%.2f,%.2f) {chosen};" % (v_best[0] + 0.04, v_best[1] + 0.02))
    L.append("\\end{axis}")
    L.append("\\end{tikzpicture}")
    with open(os.path.join(FIGS, "example-window.tex"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    # --- workspace ---------------------------------------------------------
    run = simulate(p, v_a, goal, obstacles, prm, max_steps=60)
    ob = obstacles[0]
    S = []
    S.append("% Generated by code/figures/gen_ch14_traj.py -- do not edit by hand.")
    S.append("\\begin{tikzpicture}[x=1.05cm,y=1.05cm,font=\\footnotesize]")
    S.append("\\draw[black!15,very thin] (-0.5,-1.2) grid[step=1] (5.5,1.3);")
    S.append("\\draw[->,black!50] (-0.5,0) -- (5.6,0) node[right,sbannot] {$x$};")
    S.append("\\draw[->,black!50] (0,-1.2) -- (0,1.4) node[above,sbannot] {$y$};")
    S.append("\\fill[sbobstacle] (%.2f,%.2f) circle (%.2f);" % (ob.centre[0], ob.centre[1], ob.radius))
    S.append("\\draw[black!50,dashed] (%.2f,%.2f) circle (%.2f);" % (ob.centre[0], ob.centre[1], ob.radius + prm.radius))
    for c in cands:
        end = p + c.v * prm.horizon
        style = "sbBlue!60,thin" if c.admissible else "sbRed!70,thin,densely dotted"
        S.append("\\draw[%s] (0,0) -- (%.3f,%.3f);" % (style, end[0], end[1]))
    end = p + v_best * prm.horizon
    S.append("\\draw[sbOrange,line width=1.6pt,-{Stealth[length=5pt]}] (0,0) -- (%.3f,%.3f);" % (end[0], end[1]))
    S.append("\\draw[sbpath,mark=*,mark size=1pt] plot coordinates {%s};" % polygon([(q[0], q[1]) for q in run["traj"]]))
    S.append("\\draw[sbGreen,thick] (0,0) circle (%.2f);" % prm.radius)
    S.append("\\node[sbgoal,label={[sbannot]above:goal}] at (%.1f,%.1f) {};" % (goal[0], goal[1]))
    S.append("\\node[sbannot,anchor=north east] at (-0.05,-0.25) {drone};")
    S.append("\\node[sbannot,text=sbOrange,anchor=south west] at (%.2f,%.2f) {chosen rollout};" % (end[0] + 0.05, end[1] + 0.05))
    S.append("\\node[sbannot,text=sbBlue,anchor=west] at (2.6,0.75) {closed-loop path, 13 steps};")
    S.append("\\node[sbannot,anchor=north] at (%.2f,%.2f) {obstacle};" % (ob.centre[0], ob.centre[1] - ob.radius - prm.radius - 0.05))
    S.append("\\end{tikzpicture}")
    with open(os.path.join(FIGS, "example-scene.tex"), "w") as fh:
        fh.write("\n".join(S) + "\n")
    return cands, run


def main():
    os.makedirs(DATA, exist_ok=True)
    os.makedirs(FIGS, exist_ok=True)
    metrics = run_scenes()
    write_experiment_figure()
    cands, run = write_example_figures()
    p, v_a, goal, obstacles, prm = worked_example()
    print("--- worked example: candidates (vx vy dist adm heading clearance velocity G) ---")
    for c in sorted(cands, key=lambda c: (-c.v[0], -c.v[1])):
        print("%.2f & %.2f & %.3f & %s & %.3f & %.3f & %.3f & %s \\\\" % (
            c.v[0], c.v[1], c.dist, "yes" if c.admissible else "no", c.heading, c.clearance,
            c.velocity, ("%.3f" % c.score) if c.admissible else "--"))
    print("--- worked example: closed-loop trace (step, p, v_a, chosen v, dist, h, c, s, G) ---")
    pos, vel = p.copy(), v_a.copy()
    for k in range(run["steps"]):
        v_new, cs = dwa_command(pos, vel, obstacles, goal, prm, goal)
        c = next(c for c in cs if np.allclose(c.v, v_new))
        print("%d & (%.2f, %.2f) & (%.2f, %.2f) & (%.2f, %.2f) & %.2f & %.3f & %.3f & %.3f & %.3f \\\\" % (
            k + 1, pos[0], pos[1], vel[0], vel[1], v_new[0], v_new[1], c.dist, c.heading,
            c.clearance, c.velocity, c.score))
        pos, vel = pos + v_new * prm.dt, v_new
    print("final position (%.3f, %.3f), path length %.3f m, min clearance %.3f m"
          % (run["traj"][-1][0], run["traj"][-1][1], run["path_length"], run["min_clearance"]))
    print("--- metrics per scene and weight setting ---")
    for scene, setting, r in metrics:
        end = r["traj"][-1]
        outcome = "collision" if r["collided"] else ("reached" if r["reached"] else "not reached")
        print("%s & %s & %s & %d & %.1f & %.2f & %.2f & (%.1f, %.1f) \\\\" % (
            scene, setting, outcome, r["steps"], r["path_length"], r["min_clearance"],
            r["mean_speed"], end[0], end[1]))


if __name__ == "__main__":
    main()
