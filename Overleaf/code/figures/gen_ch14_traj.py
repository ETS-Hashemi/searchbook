"""Generate the data and figures of chapter 14 (DWA) from code/ch14_dwa.py.

Writes (paths relative to Overleaf/):
    figures/data/ch14-corridor-<setting>.dat   closed-loop trajectories in the
    figures/data/ch14-utrap-<setting>.dat      corridor and the U-trap for the
                                               weight settings heading,
                                               clearance, velocity (columns
                                               t x y; at most MAX_STEPS steps)
    figures/data/ch14-utrap-path.dat           U-trap with the default weights
                                               and the heading term taken from
                                               a global path (the remedy)
    figures/ch14/experiment.tex                the two-panel pgfplots figure
    figures/ch14/example-window.tex            velocity space of the worked
                                               example (window, admissible
                                               region, candidates, choice)
    figures/ch14/example-scene.tex             workspace of the worked example
                                               with the rollouts and the
                                               closed-loop trajectory
and prints the rows of the tables of the chapter (candidate scores, closed-
loop trace, metrics per weight setting).  Everything is deterministic (no
randomness is involved).

Run from Overleaf/:   python3 code/figures/gen_ch14_traj.py
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from ch14_dwa import (Box, Disc, DwaParams, UTRAP_WAYPOINTS, WEIGHT_SETTINGS,  # noqa: E402
                      admissible_speed, corridor_scene, dwa_command, evaluate,
                      free_distance, simulate, utrap_scene, worked_example)

ROOT = os.path.join(os.path.dirname(HERE), "..")
DATA = os.path.join(ROOT, "figures", "data")
FIGS = os.path.join(ROOT, "figures", "ch14")
MAX_STEPS = 80          # 20 s of simulated time per run
STYLES = {"heading": "sbBlue,thick", "clearance": "sbOrange,thick,dashed",
          "velocity": "sbPurple,thick,dotted"}
LABELS = {"heading": "heading-dominant $(0.8,0.1,0.1)$",
          "clearance": "clearance-dominant $(0.2,0.6,0.2)$",
          "velocity": "velocity-dominant $(0.2,0.2,0.6)$"}


def write_dat(name, traj, dt):
    path = os.path.join(DATA, name)
    with open(path, "w") as fh:
        fh.write("t x y\n")
        for k, p in enumerate(traj):
            fh.write("%.3f %.4f %.4f\n" % (k * dt, p[0], p[1]))
    return path


def polygon(points):
    return " ".join("(%.4f,%.4f)" % (x, y) for x, y in points)


def circle_points(c, r, n=48):
    return [(c[0] + r * math.cos(2 * math.pi * k / n), c[1] + r * math.sin(2 * math.pi * k / n))
            for k in range(n)]


def obstacle_plots(obstacles):
    out = []
    for ob in obstacles:
        if isinstance(ob, Box):
            pts = [(ob.lo[0], ob.lo[1]), (ob.hi[0], ob.lo[1]), (ob.hi[0], ob.hi[1]), (ob.lo[0], ob.hi[1])]
        else:
            pts = circle_points(ob.centre, ob.radius)
        out.append("\\addplot[fill=sbObstacle,draw=black!40,thin,forget plot] coordinates {%s} -- cycle;"
                   % polygon(pts))
    return "\n".join(out)


def run_scenes():
    metrics = []
    runs = {}
    for scene_name, scene in (("corridor", corridor_scene), ("utrap", utrap_scene)):
        for setting, weights in [("default", DwaParams().weights)] + list(WEIGHT_SETTINGS.items()):
            p0, v0, goal, obstacles = scene()
            prm = DwaParams(weights=weights)
            run = simulate(p0, v0, goal, obstacles, prm, max_steps=300)
            metrics.append((scene_name, setting, run))
            if setting != "default":
                short = simulate(*scene(), prm, max_steps=MAX_STEPS)
                runs[(scene_name, setting)] = short
                write_dat("ch14-%s-%s.dat" % (scene_name, setting), short["traj"], prm.dt)
    p0, v0, goal, obstacles = utrap_scene()
    run = simulate(p0, v0, goal, obstacles, DwaParams(), max_steps=300,
                   waypoints=UTRAP_WAYPOINTS, lookahead=1.0)
    metrics.append(("utrap", "default + global path", run))
    write_dat("ch14-utrap-path.dat", run["traj"], DwaParams().dt)
    return metrics


