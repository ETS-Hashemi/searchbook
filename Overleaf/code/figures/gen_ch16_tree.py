"""Generate the figures of chapter 16 (RRT) as TikZ files and one data file.

Everything comes from code/ch16_rrt.py with fixed seeds.  Written files:

    figures/ch16/tree-snapshots.tex   the worked-example tree after 50, 200
                                      and 1000 iterations, with the path
    figures/ch16/voronoi.tex          a small tree and the Voronoi regions
                                      of its vertices (Voronoi bias)
    figures/ch16/jagged.tex           the longest RRT path of 100 runs
                                      against the visibility-graph shortest
                                      path (RRT is not optimal)
    figures/ch16/connect.tex          the two trees of RRT-Connect
    figures/ch16/shortcut.tex         raw path, shortcut result, pruning
    figures/ch16/scene3d.tex          the 3D box field in an oblique
                                      projection with the RRT path
    figures/data/ch16-iterations.dat  fraction of 100 runs solved within a
                                      budget of iterations, for RRT with
                                      goal bias 0, 0.05 and 0.5 and for
                                      RRT-Connect (columns iters, rrt_p00,
                                      rrt_p05, rrt_p50, connect)

The statistics quoted in the chapter text are printed at the end.
Run from Overleaf/:   python3 code/figures/gen_ch16_tree.py
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from ch16_rrt import (World, rrt, rrt_connect, shortcut, prune,  # noqa: E402
                      path_length, visibility_shortest_path,
                      worked_example_world, scene_3d)

ROOT = os.path.dirname(os.path.dirname(HERE))          # Overleaf/
FIGDIR = os.path.join(ROOT, "figures", "ch16")
DATDIR = os.path.join(ROOT, "figures", "data")
START, GOAL = np.array([1.0, 1.0]), np.array([9.0, 9.0])
ETA, P_GOAL, R_GOAL = 0.5, 0.05, 0.5
SEED = 1                 # the worked example
N_SEEDS = 100            # for the statistics
MAX_ITERS = 3000


def f(x):
    return "%.3f" % x


def write(name, lines):
    path = os.path.join(FIGDIR, name)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(path, ROOT))


def draw_edges(tree, style, transform, chunk=12):
    """One \\draw with many sub-paths per `chunk` edges."""
    out = []
    edges = tree.edges()
    for k in range(0, len(edges), chunk):
        parts = []
        for (i, j) in edges[k:k + chunk]:
            a, b = transform(tree.V[i]), transform(tree.V[j])
            parts.append("(%s,%s)--(%s,%s)" % (f(a[0]), f(a[1]), f(b[0]), f(b[1])))
        out.append("\\draw[%s] %s;" % (style, " ".join(parts)))
    return out


def draw_path(path, style, transform):
    pts = ["(%s,%s)" % (f(p[0]), f(p[1])) for p in map(transform, path)]
    out = []
    for k in range(0, len(pts), 8):
        out.append(("\\draw[%s] " % style if k == 0 else "  ")
                   + "--".join(pts[k:k + 8]) + ("--" if k + 8 < len(pts) else ";"))
    return out


def map_2d(world, transform, scale):
    """Border and box obstacles of a 2D world."""
    lo, hi = transform(world.lower), transform(world.upper)
    out = ["\\draw[black!50,very thin] (%s,%s) rectangle (%s,%s);"
           % (f(lo[0]), f(lo[1]), f(hi[0]), f(hi[1]))]
    for blo, bhi in zip(world.box_lo, world.box_hi):
        a, b = transform(blo), transform(bhi)
        out.append("\\fill[sbobstacle] (%s,%s) rectangle (%s,%s);"
                   % (f(a[0]), f(a[1]), f(b[0]), f(b[1])))
    return out


def markers(transform, scale, start=START, goal=GOAL, r_goal=R_GOAL):
    s, g = transform(start), transform(goal)
    return ["\\draw[sbGoal,dashed,thin] (%s,%s) circle (%s);"
            % (f(g[0]), f(g[1]), f(r_goal * scale)),
            "\\node[sbstart] at (%s,%s) {};" % (f(s[0]), f(s[1])),
            "\\node[sbgoal] at (%s,%s) {};" % (f(g[0]), f(g[1]))]


