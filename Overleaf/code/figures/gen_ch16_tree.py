def tree_snapshots(world):
    scale, gap = 0.42, 0.6
    res = rrt(world, START, GOAL, eta=ETA, p_goal=P_GOAL, r_goal=R_GOAL,
              max_iters=1000, seed=SEED, stop_at_goal=False,
              snapshots=(50, 200, 1000))
    lines = ["% The worked-example tree after 50, 200 and 1000 iterations",
             "%% (seed %d, eta %.1f, goal bias %.2f); generated by"
             % (SEED, ETA, P_GOAL),
             "% code/figures/gen_ch16_tree.py -- do not edit.",
             "\\begin{tikzpicture}"]
    for panel, it in enumerate((50, 200, 1000)):
        x0 = panel * (10 * scale + gap)
        tr = (lambda q, x0=x0: (x0 + q[0] * scale, q[1] * scale))
        n = res.snapshots[it]
        sub = type("T", (), {})()      # the tree truncated to n vertices
        sub.V, sub.parent, sub.n = res.tree.V, res.tree.parent, n
        sub.edges = lambda n=n, t=res.tree: [(int(t.parent[i]), i)
                                             for i in range(1, n)]
        lines += map_2d(world, tr, scale)
        lines += draw_edges(sub, "sbBlue!70,line width=0.35pt", tr)
        if it >= res.solution_iter:
            lines += draw_path(res.path, "sbpath", tr)
        lines += markers(tr, scale)
        label = "(%s) %d iterations, %d vertices" % ("abc"[panel], it, n)
        lines.append("\\node[sbannot] at (%s,%s) {%s};"
                     % (f(x0 + 5 * scale), f(-0.4), label))
    lines.append("\\end{tikzpicture}")
    write("tree-snapshots.tex", lines)
    return res


