def clip_polygon(poly, m, nrm):
    """Sutherland-Hodgman: keep the part of poly with (x - m) . nrm <= 0."""
    out = []
    for k in range(len(poly)):
        p, q = poly[k - 1], poly[k]
        fp, fq = float((p - m) @ nrm), float((q - m) @ nrm)
        if fq <= 0:
            if fp > 0:
                out.append(p + (fp / (fp - fq)) * (q - p))
            out.append(q)
        elif fp <= 0:
            out.append(p + (fp / (fp - fq)) * (q - p))
    return out


def polygon_area(poly):
    x = np.array([p[0] for p in poly])
    y = np.array([p[1] for p in poly])
    return 0.5 * abs(float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def voronoi_figure():
    world = World([0, 0], [10, 10])
    eta = 1.0
    res = rrt(world, np.array([2.0, 2.0]), np.array([99.0, 99.0]), eta=eta,
              p_goal=0.0, max_iters=14, seed=7)
    tree = res.tree
    V = tree.V[:tree.n]
    square = [np.array(c, dtype=float)
              for c in ((0, 0), (10, 0), (10, 10), (0, 10))]
    cells, areas = [], []
    for i in range(len(V)):
        poly = square
        for j in range(len(V)):
            if j != i:
                poly = clip_polygon(poly, 0.5 * (V[i] + V[j]), V[j] - V[i])
        cells.append(poly)
        areas.append(polygon_area(poly))
    big = int(np.argmax(areas))
    # a sample in the largest region and the extension it causes
    rng = np.random.default_rng(3)
    while True:
        q = world.sample(rng)
        if tree.nearest(q) == big and np.linalg.norm(q - V[big]) > 2.5:
            break
    direction = (q - V[big]) / np.linalg.norm(q - V[big])
    q_new = V[big] + eta * direction
    scale = 0.55
    tr = (lambda p: (p[0] * scale, p[1] * scale))
    lines = ["% A 15-vertex RRT in an empty square and the Voronoi regions of",
             "% its vertices; generated by code/figures/gen_ch16_tree.py.",
             "\\begin{tikzpicture}"]
    for i, poly in enumerate(cells):
        fill = "sbOrange!25" if i == big else "sbBlue!%d" % (6 + 10 * (i % 2))
        pts = "--".join("(%s,%s)" % (f(a), f(b)) for a, b in map(tr, poly))
        lines.append("\\draw[fill=%s,draw=sbBlue!50,very thin] %s--cycle;"
                     % (fill, pts))
    lines += draw_edges(tree, "sbedge", tr)
    for i, v in enumerate(V):
        a = tr(v)
        lines.append("\\fill[sbBlue] (%s,%s) circle (1.6pt);" % (f(a[0]), f(a[1])))
    s = tr(V[0])
    lines.append("\\node[sbstart] at (%s,%s) {};" % (f(s[0]), f(s[1])))
    a, b, c = tr(V[big]), tr(q), tr(q_new)
    lines.append("\\draw[sbannot,dashed,-{Stealth[length=4pt]}] (%s,%s) -- (%s,%s);"
                 % (f(a[0]), f(a[1]), f(b[0]), f(b[1])))
    lines.append("\\fill[sbRed] (%s,%s) circle (1.8pt);" % (f(b[0]), f(b[1])))
    lines.append("\\node[sbannot,anchor=west] at (%s,%s) {$q_{\\mathrm{rand}}$};"
                 % (f(b[0] + 0.1), f(b[1])))
    lines.append("\\draw[sbOrange,line width=1.4pt] (%s,%s) -- (%s,%s);"
                 % (f(a[0]), f(a[1]), f(c[0]), f(c[1])))
    lines.append("\\fill[sbOrange] (%s,%s) circle (1.8pt);" % (f(c[0]), f(c[1])))
    lines.append("\\node[sbannot,anchor=north west] at (%s,%s) {$q_{\\mathrm{new}}$};"
                 % (f(c[0] + 0.05), f(c[1] - 0.05)))
    lines.append("\\node[sbannot,anchor=south east] at (%s,%s) {$q_{\\mathrm{near}}$};"
                 % (f(a[0] - 0.05), f(a[1] + 0.05)))
    lines.append("\\end{tikzpicture}")
    write("voronoi.tex", lines)
    order = np.argsort(areas)[::-1]
    print("voronoi: %d vertices; largest region %.1f%% of the area, "
          "three largest %.1f%%, smallest %.1f%%, uniform share %.1f%%"
          % (len(V), 100 * areas[big] / 100.0,
             100 * sum(areas[k] for k in order[:3]) / 100.0,
             100 * min(areas) / 100.0, 100.0 / len(V)))


