def jagged_figure(world, worst_seed):
    res = rrt(world, START, GOAL, eta=ETA, p_goal=P_GOAL, r_goal=R_GOAL,
              max_iters=MAX_ITERS, seed=worst_seed)
    ref, ref_len = visibility_shortest_path(world, START, GOAL)
    scale = 0.5
    tr = (lambda q: (q[0] * scale, q[1] * scale))
    lines = ["%% The longest of 100 RRT paths (seed %d) against the shortest"
             % worst_seed,
             "% path; generated by code/figures/gen_ch16_tree.py.",
             "\\begin{tikzpicture}"]
    lines += map_2d(world, tr, scale)
    lines += draw_edges(res.tree, "sbBlue!30,line width=0.3pt", tr)
    lines += draw_path(ref, "sbpathalt", tr)
    lines += draw_path(res.path, "sbpath", tr)
    lines += markers(tr, scale)
    lines.append("\\end{tikzpicture}")
    write("jagged.tex", lines)
    print("jagged: seed %d, RRT path %.2f, shortest %.2f, ratio %.2f, "
          "solution at iteration %d" % (worst_seed, path_length(res.path),
                                        ref_len, path_length(res.path) / ref_len,
                                        res.solution_iter))


def connect_figure(world):
    res = rrt_connect(world, START, GOAL, eta=ETA, max_iters=MAX_ITERS, seed=SEED)
    scale = 0.5
    tr = (lambda q: (q[0] * scale, q[1] * scale))
    lines = ["%% RRT-Connect on the worked-example map (seed %d); generated by"
             % SEED, "% code/figures/gen_ch16_tree.py.", "\\begin{tikzpicture}"]
    lines += map_2d(world, tr, scale)
    lines += draw_edges(res.tree, "sbBlue!70,line width=0.35pt", tr)
    lines += draw_edges(res.tree_goal, "sbOrange!80,line width=0.35pt", tr)
    lines += draw_path(res.path, "sbpath", tr)
    lines += markers(tr, scale)
    lines.append("\\end{tikzpicture}")
    write("connect.tex", lines)
    print("connect: seed %d solved at iteration %d with %d + %d vertices, "
          "length %.2f" % (SEED, res.iterations, res.tree.n, res.tree_goal.n,
                           path_length(res.path)))


def shortcut_figure(world, res):
    raw = res.path
    sc = shortcut(raw, world, n_tries=100, seed=0)
    pr = prune(raw, world)
    scale = 0.5
    tr = (lambda q: (q[0] * scale, q[1] * scale))
    lines = ["% Raw RRT path of the worked example, after random shortcutting",
             "% and after greedy pruning; generated by",
             "% code/figures/gen_ch16_tree.py.", "\\begin{tikzpicture}"]
    lines += map_2d(world, tr, scale)
    lines += draw_path(raw, "black!45,line width=0.8pt", tr)
    lines += draw_path(sc, "sbpath", tr)
    lines += draw_path(pr, "sbpathalt", tr)
    for p in pr:
        a = tr(p)
        lines.append("\\fill[sbOrange] (%s,%s) circle (1.5pt);" % (f(a[0]), f(a[1])))
    lines += markers(tr, scale)
    lines.append("\\end{tikzpicture}")
    write("shortcut.tex", lines)
    print("shortcut: raw %.2f (%d vertices), shortcut %.2f (%d), prune %.2f (%d)"
          % (path_length(raw), len(raw), path_length(sc), len(sc),
             path_length(pr), len(pr)))


