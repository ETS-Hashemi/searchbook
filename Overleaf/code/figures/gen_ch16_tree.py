if __name__ == "__main__":
    os.makedirs(FIGDIR, exist_ok=True)
    os.makedirs(DATDIR, exist_ok=True)
    world = worked_example_world()
    res = tree_snapshots(world)
    print("worked example: solution at iteration %d; vertices at 50/200/1000: %s; "
          "path %d vertices, length %.3f"
          % (res.solution_iter, res.snapshots, len(res.path), path_length(res.path)))
    voronoi_figure()
    worst = statistics(world)
    jagged_figure(world, worst[0])
    connect_figure(world)
    shortcut_figure(world, res)
    scene3d_figure()
