def statistics(world):
    """Iterations to solution over N_SEEDS seeds for four planners."""
    grid = np.arange(0, MAX_ITERS + 1, 25)
    configs = [("rrt_p00", lambda s: rrt(world, START, GOAL, eta=ETA, p_goal=0.0,
                                         r_goal=R_GOAL, max_iters=MAX_ITERS, seed=s)),
               ("rrt_p05", lambda s: rrt(world, START, GOAL, eta=ETA, p_goal=0.05,
                                         r_goal=R_GOAL, max_iters=MAX_ITERS, seed=s)),
               ("rrt_p50", lambda s: rrt(world, START, GOAL, eta=ETA, p_goal=0.5,
                                         r_goal=R_GOAL, max_iters=MAX_ITERS, seed=s)),
               ("connect", lambda s: rrt_connect(world, START, GOAL, eta=ETA,
                                                 max_iters=MAX_ITERS, seed=s))]
    columns, summary, worst = {}, {}, None
    for name, planner in configs:
        iters, verts, lens = [], [], []
        for s in range(N_SEEDS):
            r = planner(s)
            iters.append(r.solution_iter if r.solution_iter else np.inf)
            verts.append(r.n_vertices)
            if r.path is not None:
                lens.append(path_length(r.path))
                if name == "rrt_p05" and (worst is None or lens[-1] > worst[1]):
                    worst = (s, lens[-1])
        iters = np.array(iters, dtype=float)
        columns[name] = [(iters <= g).mean() for g in grid]
        solved = np.isfinite(iters)
        summary[name] = dict(success=solved.mean(),
                             median=np.median(iters[solved]),
                             mean=iters[solved].mean(),
                             vertices=np.mean(verts),
                             length=np.mean(lens), length_sd=np.std(lens),
                             length_min=np.min(lens), length_max=np.max(lens))
    path = os.path.join(DATDIR, "ch16-iterations.dat")
    with open(path, "w") as fh:
        fh.write("iters " + " ".join(c for c, _ in configs) + "\n")
        for k, g in enumerate(grid):
            fh.write("%d " % g + " ".join("%.3f" % columns[c][k]
                                          for c, _ in configs) + "\n")
    print("wrote", os.path.relpath(path, ROOT))
    for name, _ in configs:
        s = summary[name]
        print("%-8s success %.2f  iterations median %.0f mean %.0f  "
              "vertices %.0f  length %.2f +- %.2f (min %.2f, max %.2f)"
              % (name, s["success"], s["median"], s["mean"], s["vertices"],
                 s["length"], s["length_sd"], s["length_min"], s["length_max"]))
    return worst


