def scene3d_figure():
    world = scene_3d()
    s3, g3 = np.array([0.5, 0.5, 0.5]), np.array([9.5, 9.5, 9.5])
    res = rrt(world, s3, g3, eta=0.8, p_goal=0.05, r_goal=0.5, max_iters=4000,
              seed=3)
    sc = shortcut(res.path, world, n_tries=100, seed=0)
    scale = 0.5
    ey = np.array([0.5, 0.42])

    def tr(p):
        return ((p[0] + ey[0] * p[1]) * scale, (p[2] + ey[1] * p[1]) * scale)

    def poly(corners):
        return "--".join("(%s,%s)" % (f(a), f(b)) for a, b in map(tr, corners)) + "--cycle"

    lines = ["% The 3D box field in an oblique projection with the RRT tree,",
             "% the raw path and the shortcut path; generated by",
             "% code/figures/gen_ch16_tree.py.", "\\begin{tikzpicture}"]
    # floor, back walls and axes
    lines.append("\\draw[fill=black!4,draw=black!50,very thin] %s;"
                 % poly([(0, 0, 0), (10, 0, 0), (10, 10, 0), (0, 10, 0)]))
    for k in range(1, 10):
        lines.append("\\draw[black!15,very thin] %s -- %s %s -- %s;" % (
            "(%s,%s)" % tuple(map(f, tr((k, 0, 0)))), "(%s,%s)" % tuple(map(f, tr((k, 10, 0)))),
            "(%s,%s)" % tuple(map(f, tr((0, k, 0)))), "(%s,%s)" % tuple(map(f, tr((10, k, 0))))))
    lines.append("\\draw[black!50,very thin] %s;" % poly([(0, 10, 0), (10, 10, 0), (10, 10, 10), (0, 10, 10)]))
    lines.append("\\draw[black!50,very thin] %s;" % poly([(0, 0, 0), (0, 10, 0), (0, 10, 10), (0, 0, 10)]))
    for lab, p in (("$x$", (10.6, 0, 0)), ("$y$", (10, 10.8, 0)), ("$z$", (0, 0, 10.6))):
        a = tr(p)
        lines.append("\\node[sbannot] at (%s,%s) {%s};" % (f(a[0]), f(a[1]), lab))
    # boxes, far ones first
    order = sorted(range(len(world.box_lo)), key=lambda i: (-world.box_lo[i][1], world.box_lo[i][0]))
    for i in order:
        (x0, y0, z0), (x1, y1, z1) = world.box_lo[i], world.box_hi[i]
        faces = [([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)], 45),   # front
                 ([(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)], 30),   # right
                 ([(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)], 18)]   # top
        for corners, shade in faces:
            lines.append("\\draw[fill=black!%d,fill opacity=0.75,draw=black!60,very thin] %s;"
                         % (shade, poly(corners)))
    lines += draw_edges(res.tree, "sbBlue!40,line width=0.3pt", tr)
    lines += draw_path(res.path, "sbpath", tr)
    lines += draw_path(sc, "sbpathalt", tr)
    a, b = tr(s3), tr(g3)
    lines.append("\\node[sbstart] at (%s,%s) {};" % (f(a[0]), f(a[1])))
    lines.append("\\node[sbgoal] at (%s,%s) {};" % (f(b[0]), f(b[1])))
    lines.append("\\end{tikzpicture}")
    write("scene3d.tex", lines)
    print("3D: solution at iteration %d, %d vertices, raw length %.2f, "
          "shortcut %.2f, straight line %.2f"
          % (res.solution_iter, res.n_vertices, path_length(res.path),
             path_length(sc), np.linalg.norm(g3 - s3)))


