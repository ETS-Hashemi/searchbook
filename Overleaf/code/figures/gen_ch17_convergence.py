def convergence(world, wide):
    grid = np.arange(0, MAX_ITERS + 1, 25)
    grid[0] = 1
    configs = [("rrt_map", world, GAMMA_MAP, rrt_plain, False),
               ("star_map", world, GAMMA_MAP, rrt_star, False),
               ("informed_map", world, GAMMA_MAP, rrt_star, True),
               ("rrt_wide", wide, GAMMA_WIDE, rrt_plain, False),
               ("star_wide", wide, GAMMA_WIDE, rrt_star, False),
               ("informed_wide", wide, GAMMA_WIDE, rrt_star, True)]
    columns, summary = {}, {}
    for name, w, gamma, planner, informed in configs:
        costs = np.full((N_SEEDS, MAX_ITERS), np.inf)
        first, finals, checks = [], [], []
        for s in range(N_SEEDS):
            kw = dict(eta=ETA, p_goal=P_GOAL, max_iters=MAX_ITERS, seed=s)
            if planner is rrt_star:
                kw.update(gamma=gamma, informed=informed)
            r = planner(w, START, GOAL, **kw)
            costs[s] = r.history[:, 3]
            first.append(r.solution_iter if r.solution_iter else np.inf)
            finals.append(r.cost)
            checks.append(r.segment_checks)
        col = []
        for g in grid:
            c = costs[:, g - 1]
            col.append(c.mean() if np.all(np.isfinite(c)) else np.nan)
        columns[name] = col
        first = np.array(first, dtype=float)
        finals = np.array(finals)
        summary[name] = dict(
            first_median=np.median(first[np.isfinite(first)]),
            first_max=np.max(first), solved=np.isfinite(finals).mean(),
            final_mean=finals[np.isfinite(finals)].mean(),
            final_sd=finals[np.isfinite(finals)].std(),
            final_min=finals[np.isfinite(finals)].min(),
            final_max=finals[np.isfinite(finals)].max(),
            at1000=np.nanmean(np.where(np.isfinite(costs[:, 999]),
                                       costs[:, 999], np.nan)),
            checks=np.mean(checks))
    path = os.path.join(DATDIR, "ch17-convergence.dat")
    with open(path, "w") as fh:
        fh.write("iters " + " ".join(c[0] for c in configs) + "\n")
        for k, g in enumerate(grid):
            fh.write("%d " % g + " ".join(
                "nan" if np.isnan(columns[c[0]][k]) else "%.3f" % columns[c[0]][k]
                for c in configs) + "\n")
    print("wrote", os.path.relpath(path, ROOT))
    for name, _, _, _, _ in configs:
        s = summary[name]
        print("%-14s solved %.2f  first solution median %4.0f (max %4.0f)  "
              "cost at 1000: %.2f  final %.2f +- %.2f (min %.2f, max %.2f)  "
              "segment checks %.0f" % (
                  name, s["solved"], s["first_median"], s["first_max"],
                  s["at1000"], s["final_mean"], s["final_sd"], s["final_min"],
                  s["final_max"], s["checks"]))


