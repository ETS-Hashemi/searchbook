def snapshots_figure(world):
    its = (200, 1000, 3000)
    res = rrt_star(world, START, GOAL, eta=ETA, gamma=GAMMA_MAP, p_goal=P_GOAL,
                   max_iters=MAX_ITERS, seed=SEED, snapshots=its)
    scale, gap = 0.42, 0.6
    lines = ["% RRT* on the map of chapter 16 after 200, 1000 and 3000",
             "%% iterations (seed %d, eta %.1f, gamma %.1f, goal bias %.2f);"
             % (SEED, ETA, GAMMA_MAP, P_GOAL),
             "% generated by code/figures/gen_ch17_convergence.py -- do not edit.",
             "\\begin{tikzpicture}"]
    for panel, it in enumerate(its):
        x0 = panel * (10 * scale + gap)
        tr = (lambda q, x0=x0: (x0 + q[0] * scale, q[1] * scale))
        n, path, parent = res.snapshots[it]
        lines += map_2d(world, tr)
        lines += draw_edges(res.tree.V, parent, n, "sbBlue!60,line width=0.3pt", tr)
        if path is not None:
            lines += draw_path(path, "sbpath", tr)
        lines += markers(tr)
        c = res.history[it - 1, 3]
        label = "(%s) $%d$ iterations\\\\$%d$ vertices, %s" % (
            "abc"[panel], it, n, "no path yet" if not np.isfinite(c) else "cost $%.2f$" % c)
        lines.append("\\node[sbannot,align=center] at (%s,%s) {%s};"
                     % (f(x0 + 5 * scale), f(-0.55), label))
    lines.append("\\end{tikzpicture}")
    write("snapshots.tex", lines)
    return res


def ellipses_figure(wide):
    its = (1000, 2000, 3000)
    res = rrt_star(wide, START, GOAL, eta=ETA, gamma=GAMMA_WIDE, p_goal=P_GOAL,
                   max_iters=MAX_ITERS, seed=SEED, informed=True, snapshots=its)
    first_it = res.solution_iter
    values = [(first_it, res.history[first_it - 1, 3])]
    values += [(it, res.history[it - 1, 3]) for it in its]
    scale = 0.2
    tr = (lambda q: ((q[0] + 10) * scale, (q[1] + 10) * scale))
    s = res.sampler
    lines = ["% The informed set of the wide field shrinking as c_best improves",
             "%% (Informed RRT*, seed %d), with 200 samples drawn from the" % SEED,
             "% final set; generated by code/figures/gen_ch17_convergence.py.",
             "\\begin{tikzpicture}"]
    lines += map_2d(wide, tr)
    cx, cy = tr(s.centre)
    angle = math.degrees(math.atan2(GOAL[1] - START[1], GOAL[0] - START[0]))
    styles = ["sbOrange,dashed,thick", "sbOrange!80,thick", "sbPurple,thick",
              "sbPurple!80!black,very thick"]
    rng = np.random.default_rng(5)
    pts = [s.sample(rng, res.cost, wide) for _ in range(200)]
    for p in pts:
        a = tr(p)
        lines.append("\\fill[sbBlue!70] (%s,%s) circle (0.6pt);" % (f(a[0]), f(a[1])))
    for k, (it, c) in enumerate(values):
        a, b = s.semi_axes(c) * scale
        lines.append("\\draw[%s,rotate around={%s:(%s,%s)}] (%s,%s) ellipse (%s and %s);"
                     % (styles[k], f(angle), f(cx), f(cy), f(cx), f(cy), f(a), f(b)))
        # label at the far end of the transverse axis
        lx = cx + (a + 0.35) * math.cos(math.radians(angle)) * (1 if k % 2 == 0 else -1)
        ly = cy + (a + 0.35) * math.sin(math.radians(angle)) * (1 if k % 2 == 0 else -1)
        lines.append("\\node[sbannot,text=%s] at (%s,%s) {$c=%.1f$};"
                     % (styles[k].split(",")[0], f(lx), f(ly), c))
    lines += draw_path(res.path, "sbpath", tr)
    lines += markers(tr)
    lines.append("\\end{tikzpicture}")
    write("ellipses.tex", lines)
    print("ellipses (wide field, seed %d): first solution at iteration %d, "
          "c_best %s" % (SEED, first_it,
                         ", ".join("%d: %.3f" % (it, c) for it, c in values)))
    print("   informed set: %.1f%% of X at the first solution, %.1f%% at the "
          "end; %d of %d draws rejected"
          % (100 * s.measure(values[0][1]) / wide.volume(),
             100 * s.measure(res.cost) / wide.volume(), s.rejections, s.draws))
    return res


