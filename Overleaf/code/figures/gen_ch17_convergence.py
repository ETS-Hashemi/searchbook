"""Generate the algorithm-output figures and data of chapter 17.

Everything comes from code/ch17_rrt_star.py with fixed seeds.  Written:

    figures/ch17/snapshots.tex        RRT* on the map of chapter 16 after
                                      200, 1000 and 3000 iterations with the
                                      current best path (seed 1)
    figures/ch17/ellipses.tex         the informed set shrinking as c_best
                                      improves (wide field, seed 1), with
                                      the last informed samples
    figures/data/ch17-convergence.dat mean best cost against iterations for
                                      RRT, RRT* and Informed RRT* over
                                      N_SEEDS seeds on the two maps
                                      (columns: iters, rrt_map, star_map,
                                      informed_map, rrt_wide, star_wide,
                                      informed_wide; nan while some seed has
                                      no solution yet)

The numbers quoted in the chapter are printed at the end.
Run from Overleaf/:   python3 code/figures/gen_ch17_convergence.py
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from ch17_rrt_star import (rrt_star, rrt_plain, path_length,  # noqa: E402
                           worked_example_world, wide_example_world,
                           visibility_shortest_path, grid_astar_reference,
                           gamma_star, free_volume)

ROOT = os.path.dirname(os.path.dirname(HERE))          # Overleaf/
FIGDIR = os.path.join(ROOT, "figures", "ch17")
DATDIR = os.path.join(ROOT, "figures", "data")
START, GOAL = np.array([1.0, 1.0]), np.array([9.0, 9.0])
ETA, P_GOAL = 1.0, 0.05
GAMMA_MAP, GAMMA_WIDE = 13.3, 45.0
SEED, N_SEEDS, MAX_ITERS = 1, 20, 3000


def f(x):
    return "%.3f" % x


def write(name, lines):
    path = os.path.join(FIGDIR, name)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(path, ROOT))


def draw_edges(V, parent, n, style, tr, chunk=12):
    out, edges = [], [(int(parent[i]), i) for i in range(1, n)]
    for k in range(0, len(edges), chunk):
        parts = []
        for (i, j) in edges[k:k + chunk]:
            a, b = tr(V[i]), tr(V[j])
            parts.append("(%s,%s)--(%s,%s)" % (f(a[0]), f(a[1]), f(b[0]), f(b[1])))
        out.append("\\draw[%s] %s;" % (style, " ".join(parts)))
    return out


def draw_path(path, style, tr):
    pts = ["(%s,%s)" % (f(p[0]), f(p[1])) for p in map(tr, path)]
    out = []
    for k in range(0, len(pts), 8):
        out.append(("\\draw[%s] " % style if k == 0 else "  ")
                   + "--".join(pts[k:k + 8]) + ("--" if k + 8 < len(pts) else ";"))
    return out


def map_2d(world, tr):
    lo, hi = tr(world.lower), tr(world.upper)
    out = ["\\draw[black!50,very thin] (%s,%s) rectangle (%s,%s);"
           % (f(lo[0]), f(lo[1]), f(hi[0]), f(hi[1]))]
    for blo, bhi in zip(world.box_lo, world.box_hi):
        a, b = tr(blo), tr(bhi)
        out.append("\\fill[sbobstacle] (%s,%s) rectangle (%s,%s);"
                   % (f(a[0]), f(a[1]), f(b[0]), f(b[1])))
    return out


def markers(tr):
    s, g = tr(START), tr(GOAL)
    return ["\\node[sbstart] at (%s,%s) {};" % (f(s[0]), f(s[1])),
            "\\node[sbgoal] at (%s,%s) {};" % (f(g[0]), f(g[1]))]


